import { test, expect as baseExpect } from '@playwright/test';
const expect = baseExpect.configure({ timeout: 30000 });

test('instant site language, original user content, Discord and granular permission matrix', async ({ page, context }, testInfo) => {
    test.skip(process.env.BROWSER_LOCALIZATION_TEST !== '1', 'Requires isolated localization owner fixtures.');
    test.setTimeout(180000);
    await context.route(/^http:\/\/(\[::1\]|localhost|127\.0\.0\.1):5173\//, async (route) => {
        const url = new URL(route.request().url());
        await route.fulfill({ response: await route.fetch({ url: `http://127.0.0.1:4175${url.pathname}${url.search}`, maxRetries: 2 }) });
    });
    await context.routeWebSocket(/.*/, (socket) => socket.close());
    await context.route(/https:\/\/(www\.)?youtube\.com\//, (route) => route.fulfill({ contentType: route.request().resourceType() === 'script' ? 'text/javascript' : 'text/html', body: '' }));
    await context.route('https://discord.gg/p4FD5VHgbN', (route) => route.fulfill({ contentType: 'text/html', body: '<h1>Discord invite</h1>' }));
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    const base = process.env.BROWSER_APP_URL;
    await page.goto(`${base}/login`);
    await page.getByLabel('Email or username').fill('chromium@browser-test.invalid');
    await page.getByLabel('Password', { exact: true }).fill('Browser-Test-Only-9284!');
    await page.getByRole('button', { name: 'Log in', exact: true }).click();
    await expect(page).not.toHaveURL(/\/login$/);
    await page.goto(`${base}/settings/language-time`);
    let release;
    const hold = new Promise((resolve) => { release = resolve; });
    let first = true;
    await page.route('**/settings/preferences', async (route) => { if (first) { first = false; await hold; } await route.continue(); });
    await page.locator('#language').selectOption('et');
    await expect(page.getByRole('heading', { name: 'Seaded', exact: true })).toBeVisible();
    await expect(page.getByRole('link', { name: 'Avaleht', exact: true })).toBeVisible();
    release();
    await expect(page.getByRole('status')).toHaveText('Muudatused salvestatud.');
    await page.goto(`${base}/dashboard`);
    await expect(page.getByRole('heading', { name: 'Avasta', exact: true })).toBeVisible();
    await page.goto(`${base}/settings/audio`);
    await expect(page.getByRole('heading', { name: 'Heli', exact: true })).toBeVisible();
    await page.goto(`${base}/rooms/browser-shop-chromium`);
    await expect(page.locator('.sfd-message').filter({ hasText: 'Settings' }).getByText('Settings', { exact: true })).toBeVisible();
    await expect(page.locator('.sfd-message').filter({ hasText: 'Settings' }).getByText('Dashboard', { exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Veel', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Veel', exact: true }).click();
    const popupPromise = context.waitForEvent('page');
    await page.getByRole('menuitem', { name: 'Discord', exact: true }).click();
    const popup = await popupPromise;
    await popup.waitForLoadState();
    expect(popup.url()).toBe('https://discord.gg/p4FD5VHgbN');
    await popup.close();
    await page.goto(`${base}/admin#Permissions`);
    await page.getByLabel('Õiguste kategooria').selectOption('users');
    await page.getByLabel('Otsi õigusi', { exact: true }).fill('users.roles');
    const helper = page.locator('[data-role="helper"] input[type="checkbox"]');
    await expect(helper).toHaveCount(1);
    await helper.check();
    await expect(page.locator('[data-role="owner"] input[type="checkbox"]')).toBeDisabled();
    await expect(page.locator('[data-role="member"] input[type="checkbox"]')).toBeDisabled();
    await page.getByRole('button', { name: 'Salvesta õigused', exact: true }).click();
    await expect(page.getByRole('status')).toHaveText('Õigused salvestatud.');
    await page.screenshot({ path: testInfo.outputPath('permissions-et.png') });
    await page.goto(`${base}/settings/language-time`);
    await page.locator('#language').selectOption('ru');
    await expect(page.getByRole('status')).toHaveText('Изменения сохранены.');
    await expect(page.getByRole('link', { name: 'Главная', exact: true })).toBeVisible();
    await page.goto(`${base}/dashboard`);
    await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('dashboard-ru.png') });
    await page.goto(`${base}/docs`);
    await context.grantPermissions(['clipboard-read', 'clipboard-write']);
    const example = await page.locator('pre').first().textContent();
    expect(example.length).toBeGreaterThan(10);
    await page.getByRole('button', { name: 'Копировать', exact: true }).first().click();
    await expect.poll(() => page.evaluate(async () => (await navigator.clipboard.readText()).replace(/\r\n/g, '\n'))).toBe(example.replace(/\r\n/g, '\n'));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`${base}/settings/language-time`);
    await expect(page.getByRole('heading', { name: 'Язык и время', exact: true }).first()).toBeVisible();
    await expect(page.locator('#language')).toHaveValue('ru');
    await page.screenshot({ path: testInfo.outputPath('language-ru-mobile.png'), fullPage: true });
    expect(errors).toEqual([]);
});
