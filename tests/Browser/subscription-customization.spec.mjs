import { test, expect as baseExpect } from '@playwright/test';
const expect = baseExpect.configure({ timeout: 30000 });

test('subscriber saves real profile, chat and room effects and previews entrances', async ({ page, context }, testInfo) => {
    test.skip(process.env.BROWSER_PERKS_TEST !== '1', 'Requires isolated premium subscriber fixtures.');
    test.setTimeout(120000);
    await context.route(/^http:\/\/(\[::1\]|localhost|127\.0\.0\.1):5173\//, async (route) => {
        const url = new URL(route.request().url());
        await route.fulfill({ response: await route.fetch({ url: `http://127.0.0.1:4175${url.pathname}${url.search}`, maxRetries: 2 }) });
    });
    await context.routeWebSocket(/.*/, (socket) => socket.close());
    await context.route(/https:\/\/(www\.)?youtube\.com\//, (route) => route.fulfill({ contentType: route.request().resourceType() === 'script' ? 'text/javascript' : 'text/html', body: route.request().resourceType() === 'script' ? '' : '<html></html>' }));
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    const base = process.env.BROWSER_APP_URL;
    await page.goto(`${base}/login`);
    await page.getByLabel('Email or username').fill('chromium@browser-test.invalid');
    await page.getByLabel('Password', { exact: true }).fill('Browser-Test-Only-9284!');
    await page.getByRole('button', { name: 'Log in', exact: true }).click();
    await expect(page).not.toHaveURL(/\/login$/);
    await page.goto(`${base}/settings/plus`);
    const profileLink = page.locator('a[href*="/users/"]').first();
    await expect(profileLink).toHaveAttribute('href', /\/users\/\d+/);
    const profileUrl = await profileLink.getAttribute('href');
    const values = { frame: 'custom', join: 'galaxy', gradient: 'custom', ring: 'rainbow', aura: 'cosmic', profile_animation: 'shimmer', song: 'supernova', lobby: 'neon', theme: 'custom', particles: 'stars', bubble: 'glass', message: 'sparkle', typing: 'wave', reaction: 'spin', song_reaction: '💎', transition: 'prism', entrance: 'supernova', sound: 'chime', status: 'glow', palette: 'ocean', background_animation: 'stars' };
    for (const [key, value] of Object.entries(values)) await page.locator(`#perk-${key}`).selectOption(value);
    for (const [key, value] of Object.entries({ accent: '#22d3ee', secondary: '#e879f9', background: '#101828', banner: 'Live with the community', announcement: 'Welcome to the test room', join_message: 'Hello, music friends!', dedication: 'The SFD community', music: 'https://youtu.be/abcdefghijk', badges: 'premium' })) await page.locator(`#perk-${key}`).fill(value);
    await page.getByRole('button', { name: 'Save customization', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Customization saved.' })).toBeVisible();
    await page.reload();
    await expect(page.locator('#perk-song')).toHaveValue('supernova');
    const preview = page.getByLabel('Subscription effects preview');
    await page.getByRole('button', { name: 'Preview entrance', exact: true }).click();
    await expect(preview.locator('.sub-entrance')).toContainText('Hello, music friends!');
    await expect(preview.locator('.sub-entrance')).toHaveAttribute('data-effect', 'supernova');
    await page.getByRole('button', { name: 'Preview song effect', exact: true }).click();
    await expect(preview.locator('.sub-song-effect')).toHaveAttribute('data-effect', 'supernova');
    await preview.screenshot({ path: testInfo.outputPath('subscription-effects.png') });
    await page.goto(`${base}/rooms/browser-shop-chromium`);
    await expect(page.locator('.sfd-main')).toHaveAttribute('data-sub-theme', 'custom');
    await expect(page.locator('.sub-room-banner')).toContainText('Live with the community');
    await expect(page.locator('.sub-song-effect')).toHaveAttribute('data-effect', 'supernova');
    await expect(page.locator('.sub-room-effects')).toHaveAttribute('data-particles', 'stars');
    const message = page.locator('.sfd-message').filter({ hasText: 'Browser avatar persistence check' }).first();
    await expect(message).toHaveAttribute('data-bubble', 'glass');
    await expect(message.locator('.sub-name')).toHaveAttribute('data-animated', 'true');
    await expect(page.getByText('♫ Dedicated to The SFD community')).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('subscriber-room-desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: testInfo.outputPath('subscriber-room-mobile.png') });
    await page.goto(profileUrl);
    await expect(page.getByRole('heading', { name: 'Music showcase' })).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Badge showcase' })).toBeVisible();
    await expect(page.locator('.sub-profile')).toHaveAttribute('data-profile-animation', 'stars');
    await expect(page.locator('.sub-profile .sub-name')).toHaveAttribute('data-gradient', 'custom');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    const animatedName = page.locator('.sub-profile .sub-name');
    await expect(animatedName).toHaveCSS('animation-name', 'none');
    await page.screenshot({ path: testInfo.outputPath('subscriber-profile-mobile.png') });
    expect(errors).toEqual([]);
});
